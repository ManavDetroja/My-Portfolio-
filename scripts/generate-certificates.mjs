import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");
const certificatesDirectory = path.join(projectRoot, "certificates");
const detailsPath = path.join(projectRoot, "assets", "js", "data", "certificate-details.json");
const outputPath = path.join(projectRoot, "assets", "js", "data", "certificates.data.js");
const supportedExtensions = new Set([".pdf", ".png", ".jpg", ".jpeg", ".webp"]);

async function readOptionalDetails() {
  try {
    const fileContents = await fs.readFile(detailsPath, "utf8");
    return JSON.parse(fileContents);
  } catch (error) {
    if (error.code === "ENOENT") {
      return {};
    }

    throw error;
  }
}

function fileType(extension) {
  return extension === ".pdf" ? "pdf" : "image";
}

const [files, details] = await Promise.all([
  fs.readdir(certificatesDirectory, { withFileTypes: true }),
  readOptionalDetails(),
]);

const certificates = files
  .filter((file) => file.isFile() && supportedExtensions.has(path.extname(file.name).toLowerCase()))
  .map((file) => {
    const extension = path.extname(file.name).toLowerCase();
    const metadata = details[file.name] || {};

    return {
      name: path.parse(file.name).name,
      file: `certificates/${encodeURIComponent(file.name)}`,
      fileType: fileType(extension),
      ...metadata,
    };
  })
  .sort((first, second) => first.name.localeCompare(second.name));

const output = [
  "// Generated by scripts/generate-certificates.mjs. Do not edit by hand.",
  "// Run npm run build after adding a supported file to certificates/.",
  `export const certificates = ${JSON.stringify(certificates, null, 2)};`,
  "",
].join("\n");

// Some synced Windows folders mark generated files read-only after they are written.
// Clear that attribute before replacing the file so consecutive builds stay reliable.
try {
  await fs.chmod(outputPath, 0o666);
} catch (error) {
  if (error.code !== "ENOENT") {
    throw error;
  }
}

await fs.writeFile(outputPath, output, "utf8");
console.log(`Generated ${certificates.length} certificate entries.`);
